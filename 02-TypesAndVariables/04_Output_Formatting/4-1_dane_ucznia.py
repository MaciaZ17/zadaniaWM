###
# Printing student's personal data
#
name = "Adam"                                      # imię ucznia
age = 20                                           # wiek ucznia (możesz wpisać swój)
height = 180                                       # wzrost w cm (możesz wpisać swój)
print(f"My name is {name}.")                       # f-string: {name} jest podmieniane na wartość zmiennej
print(f"I am {age} years old, and my height is {height} cm.")   # wstawiamy wiek i wzrost
print(f"In 6 years I will be {age + 6} years old.")             # w nawiasach klamrowych można wstawić też wyrażenie
