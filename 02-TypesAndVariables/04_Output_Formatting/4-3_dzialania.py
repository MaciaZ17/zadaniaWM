# Wypisanie wyrażeń razem z ich wynikami.
#
a = 3                                              # pierwsza liczba
b = 5                                              # druga liczba
print(f'{a}+{b}={a+b}')                            # 3+5=8   (wyrażenie a+b liczone wewnątrz klamer)
print(f'{a}-{b}={a-b}')                            # 3-5=-2
print(f'{a}*{b}={a*b}')                            # 3*5=15
print(f'{a}/{b}={a/b}')                            # 3/5=0.6
