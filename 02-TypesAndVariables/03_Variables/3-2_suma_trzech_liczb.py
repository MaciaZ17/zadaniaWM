# A program that calculates the sum of three numbers.
#
number1 = 71                                       # pierwsza liczba
number2 = 14                                       # druga liczba
number3 = 5                                        # trzecia liczba (dodana w ramach modyfikacji)
result = number1 + number2 + number3               # sumujemy wszystkie trzy liczby
print('Number 1: ', number1)                       # wypisujemy pierwszą liczbę
print('Number 2: ', number2)                       # wypisujemy drugą liczbę
print('Number 3: ', number3)                       # wypisujemy trzecią liczbę
print('The result of summation: ', result)         # wypisujemy sumę (90)
