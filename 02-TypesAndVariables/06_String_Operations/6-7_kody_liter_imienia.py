###
# Kody liter własnego imienia.
#
name = 'John'                                      # imię (zamień na swoje; poniżej dopasuj liczbę linii)
print(f'The letter {name[0]} has a code {ord(name[0])}')   # litera o indeksie 0 i jej kod
print(f'The letter {name[1]} has a code {ord(name[1])}')   # indeks 1
print(f'The letter {name[2]} has a code {ord(name[2])}')   # indeks 2
print(f'The letter {name[3]} has a code {ord(name[3])}')   # indeks 3 (imię 4-literowe)
