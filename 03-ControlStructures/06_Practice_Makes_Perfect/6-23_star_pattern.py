# Wzór z gwiazdek: rosnący do 5, potem malejący do 1
#
for i in range(1, 6):                                        # wiersze od 1 do 5 gwiazdek
    print('* ' * i)                                          # powielamy tekst "* " i razy
for i in range(4, 0, -1):                                    # wiersze od 4 do 1 (krok -1)
    print('* ' * i)                                          # powielamy tekst "* " i razy
