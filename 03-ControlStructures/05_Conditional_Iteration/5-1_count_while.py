###
# Przykład pętli while: wypisuje 0,1,2,3,4
#
count = 0                                                    # licznik startuje od 0
while count < 5:                                             # pętla trwa, dopóki warunek jest prawdziwy
    print(count)                                             # wypisujemy aktualną wartość licznika
    count += 1                                               # zwiększamy licznik o 1 (bez tego pętla byłaby nieskończona)
