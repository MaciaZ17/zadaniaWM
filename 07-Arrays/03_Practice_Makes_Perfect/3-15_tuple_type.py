# Creates a tuple with a single word and prints its type
#
# Krotka (tuple) jest jak lista, ale nie można jej zmieniać. Zapisujemy ją w nawiasach ().
word_tuple = ('computation',)   # przecinek jest potrzebny: bez niego ('computation') to zwykły napis
print(word_tuple)               # wypisujemy krotkę
print(type(word_tuple))         # type() pokazuje rodzaj danych: <class 'tuple'>
