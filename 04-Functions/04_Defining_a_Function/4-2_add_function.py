# Example from the instructions: a function that adds two numbers
#
def add(a, b):          # tworzymy funkcję add; a i b to liczby, które do niej podamy
    result = a + b      # dodajemy a i b
    return result       # funkcja oddaje wynik

sum_value = add(5, 3)   # uruchamiamy funkcję dla 5 i 3, wynik zapisujemy w sum_value
print(sum_value)        # wypisujemy wynik (8)
